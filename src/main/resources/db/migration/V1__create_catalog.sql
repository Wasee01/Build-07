CREATE TABLE course (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject VARCHAR(12) NOT NULL,
    number VARCHAR(12) NOT NULL,
    title VARCHAR(160) NOT NULL,
    credits INTEGER NOT NULL CHECK (credits > 0),
    CONSTRAINT uq_course_code UNIQUE (subject, number)
);
CREATE TABLE term (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    registration_opens TIMESTAMP NOT NULL,
    registration_closes TIMESTAMP NOT NULL,
    CONSTRAINT ck_term_registration_window CHECK (registration_opens < registration_closes)
);
CREATE TABLE section (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    term_id BIGINT NOT NULL,
    crn VARCHAR(5) NOT NULL UNIQUE,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    seats_taken INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_section_course FOREIGN KEY (course_id) REFERENCES course(id),
    CONSTRAINT fk_section_term FOREIGN KEY (term_id) REFERENCES term(id),
    CONSTRAINT ck_section_seats CHECK (seats_taken >= 0 AND seats_taken <= capacity)
);
CREATE INDEX ix_section_course ON section(course_id);
CREATE INDEX ix_section_term ON section(term_id);
CREATE INDEX ix_course_subject ON course(subject);
