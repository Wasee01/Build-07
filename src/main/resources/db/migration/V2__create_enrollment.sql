CREATE TABLE student (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE
);
CREATE TABLE enrollment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    enrolled_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_enrollment_student FOREIGN KEY (student_id) REFERENCES student(id),
    CONSTRAINT fk_enrollment_section FOREIGN KEY (section_id) REFERENCES section(id),
    CONSTRAINT uq_enrollment_student_section UNIQUE (student_id, section_id)
);
-- The unique index already supports student_id queries through its leading column.
CREATE INDEX ix_enrollment_section ON enrollment(section_id);
